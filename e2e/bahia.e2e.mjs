// WEB-110 regression: Bahía is RETIRED from the UI; legacy game data is preserved.
// Needs a local server on :8765 serving web/ and global Playwright.
import { createRequire } from "module";
const require = createRequire(import.meta.url);
const { chromium, devices } = require(require("child_process").execSync("npm root -g").toString().trim() + "/playwright");
const ok = (label, pass) => { console.log(pass ? "PASS" : "FAIL", label); if (!pass) process.exitCode = 1; };
const browser = await chromium.launch();
const ctx = await browser.newContext({ ...devices["iPhone 14"], timezoneId: "Europe/Madrid" });
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", e => errors.push(String(e)));
page.on("dialog", d => d.accept());
await page.route(/open-meteo\.com|supabase\.co/, r => r.fulfill({ status: 503, body: "" }));
const oldGame = { rest: { "2026-11-01": true }, sessions: [{ id: "old", start: "2026-11-01T10:00:00Z", end: "2026-11-01T11:00:00Z" }], nights: { "2026-11-01": 3 }, treadmill: { "2026-11-02": true } };
const vault = { schema: 1, settings: { skin: "design", game: oldGame }, inbox: [], chat: [], spending: [], income: [], projects: [] };
await page.addInitScript(v => {
  if (sessionStorage.getItem("seeded")) return;
  sessionStorage.setItem("seeded", "1");
  sessionStorage.setItem("manuos.tab", "bahia");
  localStorage.setItem("manuos.vault", JSON.stringify(v));
}, vault);
await page.goto("http://localhost:8765/");
await page.waitForTimeout(850);
ok("legacy Bahía session now opens Hoy", (await page.locator("#tabs [data-tab='hoy']").getAttribute("aria-selected")) === "true");
ok("Bahía is absent from navigation", (await page.locator("#tabs [data-tab='bahia']").count()) === 0);
ok("Agenda has its own tab", (await page.locator("#tabs [data-tab='agenda']").count()) === 1);
ok("navigation has six useful destinations", (await page.locator("#tabs .tab").count()) === 6);
ok("no game canvas displayed", (await page.locator("#bzCanvas").count()) === 0);
await page.click("#tabs [data-tab='agenda']");
await page.waitForTimeout(200);
ok("Agenda opens from the new tab", (await page.locator("#tabs [data-tab='agenda']").getAttribute("aria-selected")) === "true");
ok("legacy game data stays byte-for-byte intact", await page.evaluate(game => JSON.stringify(JSON.parse(localStorage.getItem("manuos.vault")).settings.game) === JSON.stringify(game), oldGame));
await page.reload();
await page.waitForTimeout(700);
ok("Agenda selection survives reload", (await page.locator("#tabs [data-tab='agenda']").getAttribute("aria-selected")) === "true");
ok("no page errors", errors.length === 0);
if (errors.length) console.log(errors);
await ctx.close();
await browser.close();
console.log("DONE");
